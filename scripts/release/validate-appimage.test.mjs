import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { validateAppDir, validateAppImages } from "./validate-appimage.mjs";

const png = fileURLToPath(
  new URL("../../apps/desktop/src-tauri/icons/128x128.png", import.meta.url),
);
const cli = fileURLToPath(new URL("./validate-appimage.mjs", import.meta.url));
const unixOnly = { skip: process.platform === "win32" };

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "inkpoint-appimage-test-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const appDir = path.join(root, "Example App.AppDir");
  fs.mkdirSync(appDir);
  fs.copyFileSync(png, path.join(appDir, "Example App.png"));
  return { root, appDir, icon: path.join(appDir, ".DirIcon") };
}

test(
  "rejects the absolute .DirIcon generated by Tauri 2.11.2 even on its build machine",
  unixOnly,
  (t) => {
    const { appDir, icon } = fixture(t);
    fs.symlinkSync(path.join(appDir, "Example App.png"), icon);
    assert.ok(fs.existsSync(icon));
    assert.throws(() => validateAppDir(appDir), /relative symlink/u);
  },
);

test(
  "a relative icon link survives moving the AppDir away from its build location",
  unixOnly,
  (t) => {
    const { root, appDir, icon } = fixture(t);
    fs.symlinkSync("Example App.png", icon);
    const moved = path.join(root, "relocated.AppDir");
    fs.renameSync(appDir, moved);
    assert.doesNotThrow(() => validateAppDir(moved));
  },
);

test("accepts a regular PNG .DirIcon", (t) => {
  const { appDir, icon } = fixture(t);
  fs.copyFileSync(png, icon);
  assert.doesNotThrow(() => validateAppDir(appDir));
});

test("rejects missing and dangling icon links", unixOnly, (t) => {
  const { appDir, icon } = fixture(t);
  assert.throws(() => validateAppDir(appDir), /ENOENT/u);
  fs.symlinkSync("missing.png", icon);
  assert.throws(() => validateAppDir(appDir), /ENOENT/u);
});

test("rejects an icon link that escapes the AppDir through another symlink", unixOnly, (t) => {
  const { root, appDir, icon } = fixture(t);
  fs.copyFileSync(png, path.join(root, "outside.png"));
  fs.symlinkSync("../outside.png", path.join(appDir, "redirect.png"));
  fs.symlinkSync("redirect.png", icon);
  assert.throws(() => validateAppDir(appDir), /inside the AppDir/u);
});

test("rejects directories, truncated icons, and non-PNG content", (t) => {
  const { appDir, icon } = fixture(t);
  fs.mkdirSync(icon);
  assert.throws(() => validateAppDir(appDir), /PNG file/u);
  fs.rmdirSync(icon);
  fs.writeFileSync(icon, Buffer.from([137, 80, 78, 71]));
  assert.throws(() => validateAppDir(appDir), /PNG file/u);
  fs.writeFileSync(icon, "this is not a PNG even though it could have a .png filename");
  assert.throws(() => validateAppDir(appDir), /PNG file/u);
});

test("fails when the build directory contains no AppImage", (t) => {
  const { root } = fixture(t);
  assert.throws(() => validateAppImages(root), /No AppImages found/u);
});

test(
  "validates extracted artifacts, propagates failures, and does not modify signed bytes",
  unixOnly,
  (t) => {
    const { root, appDir, icon } = fixture(t);
    fs.symlinkSync("Example App.png", icon);
    const artifacts = path.join(root, "artifacts");
    fs.mkdirSync(artifacts);
    const extractionRecord = path.join(root, "extraction-path.txt");
    // Simulate only the runtime's extraction protocol; no Linux binary is needed
    // to test the artifact gate and cleanup on macOS.
    const runtime = `#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
if (process.argv[2] !== '--appimage-extract') process.exit(2);
fs.writeFileSync(${JSON.stringify(extractionRecord)}, process.cwd());
fs.cpSync(${JSON.stringify(appDir)}, path.join(process.cwd(), 'squashfs-root'), {
  recursive: true, verbatimSymlinks: true,
});
`;
    for (const arch of ["amd64", "aarch64"]) {
      fs.writeFileSync(path.join(artifacts, `Example_1.0.0_${arch}.AppImage`), runtime, {
        mode: 0o755,
      });
    }
    assert.doesNotThrow(() => validateAppImages(artifacts));
    assert.equal(fs.existsSync(fs.readFileSync(extractionRecord, "utf8")), false);
    for (const name of fs.readdirSync(artifacts)) {
      assert.equal(fs.readFileSync(path.join(artifacts, name), "utf8"), runtime);
    }

    fs.unlinkSync(icon);
    fs.symlinkSync(path.join(appDir, "Example App.png"), icon);
    const result = spawnSync(process.execPath, [cli, artifacts], { encoding: "utf8" });
    assert.equal(result.status, 1);
    assert.match(result.stderr, /Invalid AppImage.*relative symlink/u);
    assert.equal(fs.existsSync(fs.readFileSync(extractionRecord, "utf8")), false);

    const failedRuntime = path.join(artifacts, "Example_1.0.0_aarch64.AppImage");
    fs.writeFileSync(failedRuntime, "#!/bin/sh\nexit 3\n");
    assert.throws(() => validateAppImages(artifacts), /Invalid AppImage/u);
  },
);
