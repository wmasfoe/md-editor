type RecursiveStringRecord<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends Record<string, unknown>
      ? RecursiveStringRecord<T[K]>
      : T[K];
};

export type TranslationSchema = RecursiveStringRecord<typeof zh>;
