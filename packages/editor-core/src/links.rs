//! Link targets: in-document anchors and what may leave the app.
//!
//! Two decisions live here, both from
//! `docs/agent/specs/editor_interaction_tab_and_links_spec.md`:
//!
//! * **Where `#fragment` goes.** A fragment must scroll inside the document. The
//!   audit found `Cmd+click` on `[跳转](#target)` handing `#target` to the
//!   external opener, which cannot resolve it.
//! * **What may be opened externally.** Only a whitelist leaves the app.
//!   `javascript:`, `data:` and `file:` are rejected while staying editable
//!   text, and local resources and fragments are never external.
//!
//! Anchor matching is deliberately tolerant. A table of contents is hand-written
//! or generated by some other tool, so its fragments disagree about full-width
//! punctuation (`：`, `、`, `？`, `（`, `）`), percent-encoding and case. The
//! contract is: try exact, then a loose key, and if nothing matches report a miss
//! without moving the caret or touching the document.

use std::ops::Range;

use crate::{BlockKind, MarkdownDocument, SourceBlock};

/// Where a link target points.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum LinkTarget {
    /// A heading in this document. `offset` is the heading's start.
    Anchor { offset: usize },
    /// The top of the document, for an empty fragment (`#`).
    DocumentTop,
    /// A whitelisted external URL.
    External(String),
    /// A local file or resource, resolved by the host.
    Local(String),
    /// A fragment that matched no heading. Carries the fragment for the message.
    MissingAnchor(String),
    /// A scheme that must not be opened (`javascript:`, `data:`, `file:`).
    Rejected(String),
}

/// Classifies `destination` against `source`.
///
/// `source` is needed for fragments: whether one resolves depends on the
/// document's headings.
pub fn classify(source: &str, destination: &str) -> LinkTarget {
    let destination = destination.trim();
    if destination.is_empty() {
        return LinkTarget::Rejected(String::new());
    }

    if let Some(fragment) = destination.strip_prefix('#') {
        // An empty fragment is the documented "back to top" case.
        if fragment.is_empty() {
            return LinkTarget::DocumentTop;
        }
        return match resolve_anchor(source, fragment) {
            Some(offset) => LinkTarget::Anchor { offset },
            None => LinkTarget::MissingAnchor(fragment.to_owned()),
        };
    }

    match scheme_of(destination) {
        // A whitelisted scheme may be handed to the system opener.
        Some(scheme) if is_openable_scheme(scheme) => LinkTarget::External(destination.to_owned()),
        // A known-but-refused scheme stays as editable text.
        Some(scheme) if is_refused_scheme(scheme) => LinkTarget::Rejected(destination.to_owned()),
        // Any other scheme (including a bare Windows drive letter) is local.
        Some(_) => LinkTarget::Local(destination.to_owned()),
        // No scheme: a relative path or a bare host-less reference.
        None => LinkTarget::Local(destination.to_owned()),
    }
}

/// The scheme before `:`, lowercased, when the text looks like a URL.
fn scheme_of(destination: &str) -> Option<&str> {
    let colon = destination.find(':')?;
    let scheme = &destination[..colon];
    if scheme.is_empty() || !scheme.chars().next()?.is_ascii_alphabetic() {
        return None;
    }
    if !scheme
        .chars()
        .all(|ch| ch.is_ascii_alphanumeric() || matches!(ch, '+' | '-' | '.'))
    {
        return None;
    }
    Some(scheme)
}

fn is_openable_scheme(scheme: &str) -> bool {
    matches!(
        scheme.to_ascii_lowercase().as_str(),
        "http" | "https" | "mailto"
    )
}

fn is_refused_scheme(scheme: &str) -> bool {
    matches!(
        scheme.to_ascii_lowercase().as_str(),
        "javascript" | "data" | "file" | "vbscript" | "blob"
    )
}

/// One ATX heading and its anchor candidates.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Heading {
    /// Byte offset of the heading line's start.
    pub offset: usize,
    /// Visible text with inline syntax removed.
    pub text: String,
    /// GitHub-compatible slug.
    pub slug: String,
}

/// Extracts ATX headings in document order.
///
/// Only `#`-prefixed headings are included, matching the outline scope the spec
/// names. Setext headings and `#` inside fenced code are out of scope.
///
/// Slugs are de-duplicated the way GitHub does it: the first occurrence keeps the
/// bare slug and later ones get `-1`, `-2`, ... That is what makes a generated
/// table of contents reach the right heading when a document repeats a title.
pub fn headings(source: &str) -> Vec<Heading> {
    let Ok(blocks) = MarkdownDocument::new(source).blocks() else {
        return Vec::new();
    };
    let mut out = Vec::new();
    collect_headings(&blocks, source, &mut out);
    deduplicate_slugs(&mut out);
    out
}

/// Appends `-1`, `-2`, ... to repeated slugs, skipping any suffix already taken.
fn deduplicate_slugs(headings: &mut [Heading]) {
    let mut used: std::collections::HashSet<String> = std::collections::HashSet::new();
    for heading in headings.iter_mut() {
        if used.insert(heading.slug.clone()) {
            continue;
        }
        let base = heading.slug.clone();
        let mut suffix = 1usize;
        loop {
            let candidate = format!("{base}-{suffix}");
            if used.insert(candidate.clone()) {
                heading.slug = candidate;
                break;
            }
            suffix += 1;
        }
    }
}

fn collect_headings(blocks: &[SourceBlock], source: &str, out: &mut Vec<Heading>) {
    for block in blocks {
        if let BlockKind::Heading { .. } = block.kind {
            let raw = source.get(block.content_range.clone()).unwrap_or_default();
            let text = visible_text(raw);
            out.push(Heading {
                offset: block.range.start,
                slug: heading_slug(&text),
                text,
            });
        }
        collect_headings(&block.children, source, out);
    }
}

/// Strips inline Markdown syntax so the slug is built from visible text.
///
/// The contract names exactly this set: emphasis markers, strikethrough, code
/// ticks, link and image targets, and HTML tags. Leaving them in would put
/// `**` into the slug and make a hand-written table of contents miss.
fn visible_text(raw: &str) -> String {
    let mut out = String::with_capacity(raw.len());
    let mut chars = raw.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            // Emphasis, strikethrough and code markers are not content.
            '*' | '~' | '`' => {}
            // Drop an HTML tag wholesale.
            '<' => {
                for inner in chars.by_ref() {
                    if inner == '>' {
                        break;
                    }
                }
            }
            // `[label](target)` keeps the label, drops the target; `![alt](src)`
            // keeps the alt.
            '[' => {
                let mut label = String::new();
                let mut depth = 1usize;
                for inner in chars.by_ref() {
                    match inner {
                        '[' => depth += 1,
                        ']' => {
                            depth -= 1;
                            if depth == 0 {
                                break;
                            }
                        }
                        _ => {}
                    }
                    if depth > 0 {
                        label.push(inner);
                    }
                }
                // Skip the destination, if one follows.
                if chars.peek() == Some(&'(') {
                    chars.next();
                    for inner in chars.by_ref() {
                        if inner == ')' {
                            break;
                        }
                    }
                }
                out.push_str(&visible_text(&label));
            }
            '!' => {
                // `![alt](src)` already handled by the `[` arm; a lone `!` is text.
                if chars.peek() != Some(&'[') {
                    out.push(ch);
                }
            }
            other => out.push(other),
        }
    }
    out.trim().to_owned()
}

/// GitHub-compatible heading slug.
///
/// Lowercased; Unicode punctuation, symbols and emoji dropped; whitespace becomes
/// `-`; `-` and `_` kept. This is what a table of contents generated by GitHub
/// would produce, which is the common case for a hand-written one.
pub fn heading_slug(text: &str) -> String {
    let mut slug = String::with_capacity(text.len());
    let mut pending_space = false;
    for ch in text.chars() {
        if ch.is_whitespace() {
            pending_space = !slug.is_empty();
            continue;
        }
        if is_slug_punctuation(ch) {
            continue;
        }
        if pending_space {
            slug.push('-');
            pending_space = false;
        }
        for lower in ch.to_lowercase() {
            slug.push(lower);
        }
    }
    slug
}

/// Whether `ch` is dropped from a slug.
///
/// Letters, digits, `-` and `_` are kept. Everything classified as punctuation or
/// a symbol is dropped, which covers the full-width marks a CJK table of contents
/// mixes in, and emoji.
fn is_slug_punctuation(ch: char) -> bool {
    if ch.is_alphanumeric() || matches!(ch, '-' | '_') {
        return false;
    }
    // A non-alphanumeric, non-space character is punctuation or a symbol. Both
    // are dropped, matching GitHub's behaviour for CJK punctuation.
    !ch.is_alphanumeric()
}

/// Loose comparison key: letters and digits only, lowercased.
///
/// Used after an exact match fails. Dropping punctuation, whitespace and hyphens
/// absorbs the differences between a hand-written fragment and the generator's
/// slug.
fn loose_key(text: &str) -> String {
    text.chars()
        .filter(|ch| ch.is_alphanumeric())
        .flat_map(|ch| ch.to_lowercase())
        .collect()
}

/// Resolves a fragment to the heading's byte offset.
///
/// Order is exact slug, then the loose key. Returns `None` when nothing matches,
/// which the caller reports as a miss without moving the caret.
pub fn resolve_anchor(source: &str, fragment: &str) -> Option<usize> {
    let wanted = normalize_fragment(fragment);
    if wanted.is_empty() {
        return None;
    }
    let headings = headings(source);

    // 1. Exact slug.
    if let Some(heading) = headings.iter().find(|heading| heading.slug == wanted) {
        return Some(heading.offset);
    }

    // 2. Exact match against a de-duplicated slug (`title-1`, `title-2`). A
    //    generator appends these for repeated headings, so a table of contents
    //    may point at either spelling.
    if let Some(heading) = headings.iter().find(|heading| {
        heading.slug == wanted
            || heading
                .slug
                .strip_prefix(&format!("{wanted}-"))
                .is_some_and(|suffix| suffix.chars().all(|ch| ch.is_ascii_digit()))
    }) {
        return Some(heading.offset);
    }

    // 3. Loose key, whole document, first hit.
    let wanted_key = loose_key(&wanted);
    if wanted_key.is_empty() {
        return None;
    }
    headings
        .iter()
        .find(|heading| loose_key(&heading.slug) == wanted_key)
        .map(|heading| heading.offset)
}

/// Normalises a fragment for comparison.
///
/// Tolerates a leading `#`, percent-encoding and case. A fragment whose
/// percent-encoding is malformed is compared literally rather than rejected,
/// because a hand-written `#100%` is legitimate text.
fn normalize_fragment(fragment: &str) -> String {
    let fragment = fragment.trim().trim_start_matches('#');
    let decoded = percent_decode(fragment).unwrap_or_else(|| fragment.to_owned());
    decoded.trim().to_lowercase()
}

/// Percent-decodes `text`, or `None` when a `%` sequence is malformed.
///
/// Public because a link destination is a URL on both sides of the `#`: the
/// fragment resolver below decodes its half, and a host resolving the path half
/// against the filesystem must decode it the same way. Decoding only the
/// fragment left `my%20file.md` looking for a file literally named that.
pub fn percent_decode(text: &str) -> Option<String> {
    let bytes = text.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut index = 0;
    while index < bytes.len() {
        if bytes[index] == b'%' {
            let hex = bytes.get(index + 1..index + 3)?;
            let value = u8::from_str_radix(std::str::from_utf8(hex).ok()?, 16).ok()?;
            out.push(value);
            index += 3;
        } else {
            out.push(bytes[index]);
            index += 1;
        }
    }
    String::from_utf8(out).ok()
}

/// The link mark whose syntax contains `offset`, if any.
///
/// A plain click places the caret inside the link so it can be edited; the
/// caller needs the mark to know both the visible label range and the
/// destination.
pub fn link_at(marks: &[crate::InlineMark], offset: usize) -> Option<&crate::InlineMark> {
    marks.iter().find(|mark| {
        matches!(mark.kind, crate::InlineMarkKind::Link { .. })
            && mark.syntax_range.contains(&offset)
    })
}

/// The visible label range of the link containing `offset`.
pub fn link_label_at(marks: &[crate::InlineMark], offset: usize) -> Option<Range<usize>> {
    link_at(marks, offset).map(|mark| mark.range.clone())
}

#[cfg(test)]
mod tests {
    use super::*;

    const DOC: &str = "# Target\n\n## 中文标题：副标题\n\n### Repeated\n\n### Repeated\n";

    #[test]
    fn a_fragment_resolves_to_its_heading() {
        assert_eq!(resolve_anchor(DOC, "target"), Some(0));
    }

    #[test]
    fn full_width_punctuation_is_dropped_from_the_slug() {
        let heading = headings(DOC)
            .into_iter()
            .find(|heading| heading.text.starts_with("中文标题"))
            .expect("the CJK heading");
        assert_eq!(
            heading.slug, "中文标题副标题",
            "the full-width colon is dropped"
        );
    }

    #[test]
    fn a_cjk_fragment_resolves() {
        assert!(resolve_anchor(DOC, "中文标题副标题").is_some());
    }

    #[test]
    fn a_leading_hash_is_tolerated() {
        assert_eq!(
            resolve_anchor(DOC, "#target"),
            resolve_anchor(DOC, "target")
        );
    }

    #[test]
    fn percent_encoding_is_decoded() {
        assert_eq!(
            resolve_anchor(DOC, "%E4%B8%AD%E6%96%87%E6%A0%87%E9%A2%98"),
            resolve_anchor(DOC, "中文标题")
        );
    }

    #[test]
    fn a_malformed_percent_sequence_is_compared_literally() {
        // `#100%` is legitimate text, not a broken escape.
        assert_eq!(resolve_anchor("# 100%\n", "100%"), Some(0));
    }

    #[test]
    fn a_repeated_heading_matches_its_numbered_slug() {
        let repeated = resolve_anchor(DOC, "repeated");
        let second = resolve_anchor(DOC, "repeated-1");
        assert!(repeated.is_some());
        assert!(
            second.is_some_and(|offset| offset > repeated.unwrap()),
            "the numbered slug reaches the later heading"
        );
    }

    #[test]
    fn the_loose_key_absorbs_punctuation_differences() {
        // The hand-written fragment keeps a colon the generator dropped.
        assert!(resolve_anchor(DOC, "中文标题：副标题").is_some());
    }

    #[test]
    fn a_missing_fragment_returns_none() {
        assert_eq!(resolve_anchor(DOC, "no-such-heading"), None);
    }

    #[test]
    fn inline_syntax_is_stripped_from_the_slug() {
        let source = "# **Bold** and `code` and [link](https://example.com)\n";
        let heading = headings(source).into_iter().next().expect("a heading");
        assert_eq!(
            heading.slug, "bold-and-code-and-link",
            "markers and the link target are not part of the visible text"
        );
    }

    #[test]
    fn classify_routes_each_kind_of_destination() {
        assert_eq!(classify(DOC, "#target"), LinkTarget::Anchor { offset: 0 });
        assert_eq!(classify(DOC, "#"), LinkTarget::DocumentTop);
        assert_eq!(
            classify(DOC, "https://example.com"),
            LinkTarget::External("https://example.com".into())
        );
        assert_eq!(
            classify(DOC, "mailto:someone@example.com"),
            LinkTarget::External("mailto:someone@example.com".into())
        );
        assert_eq!(
            classify(DOC, "./assets/image.png"),
            LinkTarget::Local("./assets/image.png".into())
        );
        assert!(matches!(
            classify(DOC, "#nope"),
            LinkTarget::MissingAnchor(_)
        ));
    }

    #[test]
    fn a_link_is_found_by_an_offset_inside_its_syntax() {
        let source = "see [label](https://example.com) here";
        let marks = MarkdownDocument::new(source).inline_marks().unwrap();
        let inside = source.find("label").unwrap();
        let link = link_at(&marks, inside).expect("a link at the label");
        assert_eq!(
            &source[link.range.clone()],
            "label",
            "the visible label is the range to select"
        );
        assert_eq!(link_label_at(&marks, inside), Some(link.range.clone()));
    }

    #[test]
    fn a_plain_click_outside_a_link_finds_nothing() {
        let source = "plain text [label](https://example.com)";
        let marks = MarkdownDocument::new(source).inline_marks().unwrap();
        assert_eq!(link_at(&marks, 0), None);
        assert_eq!(link_label_at(&marks, 0), None);
    }

    #[test]
    fn dangerous_schemes_are_rejected_rather_than_opened() {
        for target in [
            "javascript:alert(1)",
            "data:text/html,<script>",
            "file:///etc/passwd",
        ] {
            assert!(
                matches!(classify(DOC, target), LinkTarget::Rejected(_)),
                "{target} must not be openable"
            );
        }
    }
}
